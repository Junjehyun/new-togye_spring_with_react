package com.yama331.togye.entity;

/**
 * 베팅 하나의 결과가 될 수 있는 값은 딱 이 4가지에서 결정!
 * 
 * 이런걸 "열거형(enum)"이라고 부른다.
 * 라라벨의 {@code enum BetResult: string{ case Pending = 'PENDING'; ...}}
 * 과 완전히 같은 개념이다. "이 값은 몇 개 정해진 후보중 하나만 될 수 있다"를 자바 타입 시스템으로
 * 못박아 두는 것. 그냥 String으로 "WIN", "LOSE" 라고 쓸 수도 있지만, 그러면 "WNI" 처럼
 * 오타를 내도 컴파일할 때 (=코드를 실행하기 전에) 아무도 못 잡아준다. 
 * enum으로 정의해두면, 이 4개 이름 말고 다른 걸 쓰는 순간 코드가 아예 빨간 줄이 뜨고, 
 * 실행조차 안된다. 실수를 일찍 잡아준다는 뜻.
 */
public enum BetResult {

    /**아직 경기가 안 끝나서, 이겼는지 졌는지 모르는 상태. "결과 대기 중" 이라는 뜻. */
    PENDING,
    /**적중! */
    WIN,
    /**미적중 ㅜㅜ */
    LOSE,
    /**적특 */
    PUSH
}
